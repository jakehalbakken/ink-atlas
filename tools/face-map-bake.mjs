// Finds MediaPipe's 478 face landmarks on the 3D head and writes src/face-map.js: each landmark as a
// body triangle and barycentric weights, so "My face" can line a selfie up with the head on any body
// shape. Run after a build: node tools/shot.mjs shots/face-bake.png tools/face-map-bake.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
export default async function (p) {
  await p.waitForFunction(() => window.__ink && window.__ink.ready(), { timeout: 30000 });
  await p.addStyleTag({ content: 'body *{visibility:hidden!important} canvas{visibility:visible!important}' });
  const W = 1180, H = 820;
  await p.evaluate(() => {
    const P = window.__ink.positions(); let x = 0, y = 0, z = 0, n = 0;
    for (let v = 13380; v < 13524; v++) { x += P[v * 3]; y += P[v * 3 + 1]; z += P[v * 3 + 2]; n++; }
    const g = window.__ink.goal, c = window.__ink.cur;
    Object.assign(g, { theta: 0, phi: Math.PI / 2, roll: 0, tx: 0, ty: y / n - 0.035, tz: z / n, r: 0.62 });
    c.r = g.r * 1.02;
  });
  await p.waitForFunction(() => window.__ink.settled(), { timeout: 30000 });
  await new Promise((r) => setTimeout(r, 300));
  const shot = await p.screenshot({ encoding: 'base64' }); writeFileSync('/tmp/claude-0/facehead.png', Buffer.from(shot, 'base64'));
  const lm = await p.evaluate((u) => window.__ink.findFace(u), 'data:image/png;base64,' + shot);
  if (!lm) throw new Error('no face found on the 3D head');
  const map = [], misses = [];
  for (let i = 0; i < lm.length; i++) {
    // a point on the very edge of the jaw can miss the silhouette: step in towards the nose
    let h = null;
    for (let s = 0; s <= 1 && !h; s += 0.01) {
      const x = (lm[i][0] + (lm[1][0] - lm[i][0]) * s * 0.15) * W, y = (lm[i][1] + (lm[1][1] - lm[i][1]) * s * 0.15) * H;
      h = await p.evaluate((x, y) => window.__ink.hitBody(x, y), x, y);
    }
    if (!h || !h.bary) { misses.push(i); map.push(0, 0, 0); continue; }
    map.push(h.faceIndex, +h.bary[1].toFixed(5), +h.bary[2].toFixed(5));
  }
  if (misses.length) throw new Error('landmarks off the body: ' + misses.join(','));
  // a picture with the landmarks on it, to check by eye
  await p.evaluate((pts) => { const c = document.createElement('canvas'); c.width = innerWidth; c.height = innerHeight; c.style.cssText = 'position:fixed;inset:0;z-index:99;visibility:visible!important;pointer-events:none'; const g = c.getContext('2d'); g.fillStyle = '#0f0'; for (const [x, y] of pts) g.fillRect(x * innerWidth - 1, y * innerHeight - 1, 2, 2); document.documentElement.append(c); }, lm);
  await p.screenshot({ path: resolve(import.meta.dirname, '..', 'shots', 'face-bake-points.png') });
  writeFileSync(resolve(import.meta.dirname, '..', 'src', 'face-map.js'), '// Generated by tools/face-map-bake.mjs: MediaPipe face landmark i sits on body triangle\n// FACE_MAP[i*3] with barycentric weights (1 - w1 - w2, FACE_MAP[i*3+1], FACE_MAP[i*3+2]).\nexport const FACE_MAP = ' + JSON.stringify(map) + ';\n');
  console.log('baked', lm.length, 'landmarks');
}
