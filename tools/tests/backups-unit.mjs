import assert from 'node:assert/strict';
import { dayKey, backupName, parseBackupName, toPrune, listBackups, dayWords, backupBody, readBackupBody } from '../../src/backups.js';
assert.equal(dayKey(new Date(2026, 10, 7, 23, 59)), '2026-11-07');
const id = '3f2b1c4e-1111-2222-3333-444455556666';
assert.equal(backupName(id, '2026-11-27'), id + '_2026-11-27.json');
assert.equal(backupName('../x', '2026-11-27'), null);
assert.equal(backupName(id, 'today'), null);
assert.deepEqual(parseBackupName(id + '_2026-11-27.json'), { projectId: id, day: '2026-11-27', file: id + '_2026-11-27.json' });
assert.equal(parseBackupName('abc.png'), null);
assert.equal(parseBackupName('a/b_2026-11-27.json'), null);
const names = [];
for (let i = 1; i <= 35; i++) names.push(`p1_2026-10-${String(i).padStart(2, '0')}.json`.replace('10-32', '11-01').replace('10-33', '11-02').replace('10-34', '11-03').replace('10-35', '11-04'));
names.push('p2_2026-01-01.json', 'img_abc', 'p2_2026-01-02.json');
const gone = toPrune(names, 30);
assert.equal(gone.length, 5);
assert.ok(gone.every((n) => n.startsWith('p1_2026-10-0')));
assert.ok(!gone.includes('p1_2026-11-04.json'));
assert.deepEqual(toPrune(['p_2026-01-01.json'], 0), []); // never the newest one
const l = listBackups(['b_2026-11-26.json', 'a_2026-11-27.json', 'c_2026-11-27.json'], (p) => ({ a: 'Zed', c: 'Arm' })[p]);
assert.deepEqual(l.map((x) => x.projectId), ['c', 'a', 'b']);
assert.equal(l[2].name, '');
const now = new Date(2026, 10, 27, 10);
assert.equal(dayWords('2026-11-27', now), 'Today');
assert.equal(dayWords('2026-11-26', now), 'Yesterday');
assert.ok(/Nov/.test(dayWords('2026-11-20', now)));
const body = backupBody({ projectId: id, name: 'Mine', state: { v: 2, tattoos: [{ id: 't', img: 'k1' }] }, imageKeys: ['k1', 5] });
const back = readBackupBody(body);
assert.equal(back.name, 'Mine'); assert.deepEqual(back.keys, ['k1']); assert.equal(back.state.tattoos.length, 1); assert.equal(back.projectId, id);
assert.throws(() => readBackupBody('{"x":1}'));
assert.throws(() => readBackupBody('nope'));
console.log('backups-unit ok');
