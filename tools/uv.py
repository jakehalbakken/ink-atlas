# Bake MakeHuman's texture coordinates (UVs) for the body and eyes into src/body-uv.js.
# Corner order matches BODY_IDX in src/body.js exactly: the same faces, in the same
# order, fan-triangulated the same way as tools/mesh.py does. Kept in its own file so
# the app only loads it when someone exports a UV-mapped model.
# Usage: python3 -I tools/uv.py data-src src/body-uv.js
import base64, os, struct, sys

src_dir, out = sys.argv[1], sys.argv[2]
PARTS = [('body', {'body'}), ('eyes', {'helper-l-eye', 'helper-r-eye'})]
part_of = {g: name for name, gs in PARTS for g in gs}
vt = []; faces = {name: [] for name, _ in PARTS}; g = None
for line in open(os.path.join(src_dir, 'base.obj'), encoding='utf-8', errors='replace'):
    if line.startswith('vt '):
        p = line.split(); vt.append((float(p[1]), float(p[2])))
    elif line.startswith('g '):
        g = line.split()[1]
    elif line.startswith('f ') and g in part_of:
        faces[part_of[g]].append([int(t.split('/')[1]) - 1 for t in line.split()[1:]])

corners = []
for f in faces['body'] + faces['eyes']:
    for i in range(1, len(f) - 1):
        corners += [f[0], f[i], f[i + 1]]
q = lambda x: max(0, min(65535, int(round(x * 65535))))
data = b''.join(struct.pack('<2H', q(vt[c][0]), q(vt[c][1])) for c in corners)
body_tris = sum(len(f) - 2 for f in faces['body'])
open(out, 'w').write('\n'.join([
    '// Generated by tools/uv.py. Do not edit by hand.',
    '// Per-corner texture coordinates for BODY_IDX (body then eyes), u and v as uint16 / 65535.',
    'export const UV_TRIS=%d;' % (len(corners) // 3),
    'export const UV_BODY_TRIS=%d;' % body_tris,
    'export const UV_CORNERS="%s";' % base64.b64encode(data).decode(),
]) + '\n')
print('triangles', len(corners) // 3, 'body', body_tris, 'bytes', os.path.getsize(out))
