// Finds MediaPipe's 478 face landmarks on the plain 3D head, seen straight on, and writes their
// depth to src/face-depth.js (in face widths, cheek to cheek, less the mean). A selfie's landmark
// depth minus these is that person's own depth, so Add my face can shape the nose, brow and chin
// from front to back too. Run after a build: node tools/shot.mjs shots/face-depth.png tools/face-depth-bake.mjs
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
export default async function (p) {
  await p.waitForFunction(() => window.__ink && window.__ink.ready(), { timeout: 30000 });
  await p.addStyleTag({ content: 'body *{visibility:hidden!important} canvas{visibility:visible!important}' });
  const W = 1180;
  await p.evaluate(() => {
    const P = window.__ink.positions(); let x = 0, y = 0, z = 0, n = 0;
    for (let v = 13380; v < 13524; v++) { x += P[v * 3]; y += P[v * 3 + 1]; z += P[v * 3 + 2]; n++; }
    const g = window.__ink.goal, c = window.__ink.cur;
    Object.assign(g, { theta: 0, phi: Math.PI / 2, roll: 0, tx: 0, ty: y / n - 0.035, tz: z / n, r: 0.62 });
    c.r = g.r * 1.02;
  });
  await p.waitForFunction(() => window.__ink.settled(), { timeout: 30000 });
  await new Promise((r) => setTimeout(r, 300));
  const shot = await p.screenshot({ encoding: 'base64' });
  const lm = await p.evaluate((u) => window.__ink.findFace(u), 'data:image/png;base64,' + shot);
  if (!lm || !lm.every((q) => Number.isFinite(q[2]))) throw new Error('no face with depth found on the 3D head');
  const fw = Math.hypot(lm[454][0] - lm[234][0], (lm[454][1] - lm[234][1]) * (820 / W));
  const z = lm.map((q) => q[2] / fw);
  const m = z.reduce((a, b) => a + b, 0) / z.length;
  const out = z.map((v) => +(v - m).toFixed(4));
  writeFileSync(resolve(import.meta.dirname, '..', 'src', 'face-depth.js'), '// Generated by tools/face-depth-bake.mjs: MediaPipe\'s depth for each of its 478 face landmarks on\n// the plain 3D head seen straight on, in face widths (cheek to cheek), less the mean. Nearer is smaller.\nexport const FACE_DEPTH = ' + JSON.stringify(out) + ';\n');
  console.log('baked depth for', out.length, 'landmarks; nose tip', out[1], 'cheek', out[234]);
}
