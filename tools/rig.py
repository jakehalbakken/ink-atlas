"""Isolated pose-data bake. python3 -I tools/rig.py data-src src/rig.js
Reuses the mesh baker's pre-output definitions to preserve exact vertex mapping.
Never runs its file writer or modifies body.js. Rejects an out-of-sync body bake.
"""
import base64, hashlib, json, math, pathlib, struct, sys
source, output = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
mesh_path = pathlib.Path(__file__).with_name('mesh.py')
code = mesh_path.read_text()
ns = {}
exec(compile(code[:code.index('def peak(')], str(mesh_path), 'exec'), ns)
rig = json.loads((source/'rig/default.mhskel').read_text())
weights = json.loads((source/'rig/default_weights.mhw').read_text())['weights']
body_file = output.with_name('body.js').read_text()
base = base64.b64encode(b''.join(struct.pack('<3f', *p) for p in ns['basepos'])).decode()
assert 'BODY_BASE="'+base+'"' in body_file, 'body bake differs; do not integrate stale rig'
# Parent-first topology, no reliance on input dictionary order.
names, visiting = [], set()
def visit(name):
    if name in names: return
    assert name not in visiting, 'cyclic skeleton'
    visiting.add(name)
    parent = rig['bones'][name]['parent']
    if parent: visit(parent)
    visiting.remove(name); names.append(name)
for name in rig['bones']: visit(name)
assert all(name in names for name in weights)
joint_names = sorted(rig['joints']); ji = {k:i for i,k in enumerate(joint_names)}
bones = [{'name':name, 'parent':names.index(b['parent']) if b['parent'] else -1,
          'head':ji[b['head']], 'tail':ji[b['tail']]} for name in names for b in [rig['bones'][name]]]
raw_weights = {}
for bone, pairs in weights.items():
    for v,w in pairs:
        assert math.isfinite(w) and w >= 0
        raw_weights.setdefault(v,{})[names.index(bone)] = w
combos = [{i:1.0} for i in ns['plain']] + ns['gpts']
offsets, ids, values = [0], [], []
for combo in combos:
    combined = {}
    for v,f in combo.items():
        for b,w in raw_weights.get(v,{}).items(): combined[b] = combined.get(b,0)+w*f
    total = sum(combined.values()); assert total > 0, 'unweighted retained vertex'
    for b,w in sorted(combined.items()):
        if w > 0: ids.append(b); values.append(w/total)
    offsets.append(len(ids))
# Re-evaluate the exact target name/composition declarations, but on joint source
# vertices (including helper vertices intentionally absent from the body bake).
ns['needed'] = {v for a in rig['joints'].values() for v in a}
def joint_spread(raw):
    return {ji[name]:tuple(sum(raw.get(v,(0,0,0))[axis] for v in verts)/len(verts) for axis in range(3))
            for name,verts in rig['joints'].items()}
ns['spread'] = joint_spread
exec(compile(code[code.index('T = {}'):code.index('def peak(')], str(mesh_path), 'exec'),ns)
joint_base = joint_spread({v:ns['verts'][v] for v in ns['needed']})
pack = lambda fmt, vals: base64.b64encode(struct.pack('<'+str(len(vals))+fmt,*vals)).decode()
flat = lambda d: [c for i in range(len(joint_names)) for c in d[i]]
data = {'version':1, 'meshSourceSHA256':hashlib.sha256(code.encode()).hexdigest(),
        'bodyBaseSHA256':hashlib.sha256(base.encode()).hexdigest(), 'vertexCount':len(combos),
        'maxInfluences':max(offsets[i+1]-offsets[i] for i in range(len(combos))),
        'bones':bones,'jointNames':joint_names,'jointBase':pack('d',flat(joint_base)),
        'jointTargets':{key:pack('d',flat(d)) for key,d in ns['T'].items()},
        'offsets':pack('I',offsets),'boneIds':pack('H',ids),'weights':pack('d',values),
        'license':rig.get('license'), 'copyright':rig.get('copyright'),
        'rotationConvention':'parent-relative rotations around canonical world axes; not MakeHuman bone-roll axes'}
output.write_text('// Generated by tools/rig.py. No runtime integration yet.\nexport const RIG='+json.dumps(data,separators=(',',':'))+';\n')
print(json.dumps({k:data[k] for k in ['vertexCount','maxInfluences','license']})); print('bones',len(bones),'joints',len(joint_names),'bytes',output.stat().st_size)
